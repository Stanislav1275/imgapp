"""
Фильтры на основе свёртки: резкость, размытие в движении, тиснение, медиана.

Свёртка: берём маленькую таблицу чисел (ядро) и для каждого пикселя
умножаем соседей на соответствующие числа ядра и складываем:
    s(x, y) = сумма по соседям ядро[i][j] * r(x + i, y + j)
Результат кладём в тот же пиксель новой картинки. Края картинки дополняем отражением.
"""
import cv2
import numpy as np


def _clip_to_uint8(x):
    return np.clip(np.round(x), 0, 255).astype(np.uint8)


def convolve(img, kernel):
    """Применить ядро к изображению (цветному или серому). Работаем в дробных числах и потом обрезаем."""
    result = cv2.filter2D(img.astype(np.float32), -1, np.asarray(kernel, np.float32),
                          borderType=cv2.BORDER_REFLECT)
    return _clip_to_uint8(result)


# ----------------------------------------------------------------------
# Резкость
# ----------------------------------------------------------------------

def sharpen_kernel(strength=1.0):
    """
    Ядро резкости:   [ 0   -s    0 ]
                     [-s  1+4s  -s ]
                     [ 0   -s    0 ]
    Сумма элементов равна 1, поэтому общая яркость не меняется. Пиксель усиливается
    относительно соседей: на ровных местах ничего не происходит, на границах контраст растёт.
    При strength = 1 получается классическое ядро с центром 5.
    """
    s = strength
    return [[0, -s, 0], [-s, 1 + 4 * s, -s], [0, -s, 0]]


def sharpen(img, strength=1.0):
    return convolve(img, sharpen_kernel(strength))


# ----------------------------------------------------------------------
# Размытие в движении
# ----------------------------------------------------------------------

def motion_blur_kernel(length=15, angle=0.0):
    """
    Ядро размытия в движении: линия длиной length под углом angle (в градусах),
    все числа равны, а сумма — 1. Пиксель заменяется средним по линии, как будто
    камера двигалась вдоль этой линии во время съёмки.
    """
    length = max(1, int(length))
    size = length if length % 2 == 1 else length + 1
    kernel = np.zeros((size, size), np.float32)
    c = size // 2
    dx = np.cos(np.radians(angle)) * (length - 1) / 2
    dy = -np.sin(np.radians(angle)) * (length - 1) / 2
    cv2.line(kernel, (int(round(c - dx)), int(round(c - dy))),
             (int(round(c + dx)), int(round(c + dy))), 1.0, 1)
    return kernel / kernel.sum()


def motion_blur(img, length=15, angle=0.0):
    return convolve(img, motion_blur_kernel(length, angle))


# ----------------------------------------------------------------------
# Тиснение
# ----------------------------------------------------------------------

EMBOSS_KERNEL = [[-2, -1, 0],
                 [-1,  1, 1],
                 [ 0,  1, 2]]


def emboss(img):
    """
    Тиснение: ядро с отрицательными числами с одной стороны (верх-лево) и положительными
    с другой (низ-право) считает разность яркости вдоль диагонали, то есть подсвечивает перепады.
    Чтобы ровные участки дали нейтрально-серый цвет, обнуляем центр ядра (сумма ядра становится 0,
    ровный участок даёт 0) и прибавляем 128 к результату.
    Считаем по серому изображению и возвращаем серое (H, W).
    """
    gray = img if img.ndim == 2 else cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    kernel = np.array(EMBOSS_KERNEL, np.float32)
    kernel[1, 1] = 0                               # сумма ядра теперь 0: ровный участок даёт 0
    result = cv2.filter2D(gray.astype(np.float32), -1, kernel, borderType=cv2.BORDER_REFLECT)
    return _clip_to_uint8(result + 128)


# ----------------------------------------------------------------------
# Медианный фильтр
# ----------------------------------------------------------------------

def median(img, size=3):
    """
    Медианный фильтр: каждый пиксель заменяется медианой яркости в окне size x size
    (середина отсортированного списка). Убирает «соль и перец» (одиночные белые и чёрные точки),
    при этом края объектов остаются чёткими, в отличие от обычного размытия.
    """
    if size % 2 == 0:
        size += 1
    return cv2.medianBlur(img, size)
