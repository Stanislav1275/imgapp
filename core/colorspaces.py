"""
Перевод цвета между моделями: RGB, HEX, CMYK, HSV, HSL, YCbCr, LAB.

Как устроен модуль
------------------
Все модели переводятся ЧЕРЕЗ RGB (RGB — «хаб»). Для каждой модели две функции:
    rgb_to_X(R, G, B)  ->  значения в модели X
    X_to_rgb(...)      ->  (R, G, B)
А функция convert(...) внизу файла соединяет их: X -> RGB -> Y.

Обозначения (важно, иначе легко запутаться)
-------------------------------------------
    R, G, B   — байты 0..255 (так хранится в файле)
    r, g, b   — доли 0..1:  r = R / 255
    r_lin ... — «линейный» свет (после снятия гаммы sRGB), нужен только для XYZ/LAB

Единицы выхода:
    H    — градусы 0..360
    S, V, L (HSV/HSL), C, M, Y, K (CMYK) — доли 0..1
    Y, Cb, Cr — 0..255
    L (LAB) — 0..100, a и b — примерно -128..127

Подробный вывод всех формул — в файле color_formulas.md.
"""

# ----------------------------------------------------------------------
# Вспомогательные функции
# ----------------------------------------------------------------------

def clamp(x, low, high):
    """Обрезать число x до диапазона [low, high]."""
    return max(low, min(high, x))


def to_byte(x):
    """Дробное число -> целый байт 0..255 (с округлением и обрезкой)."""
    return int(round(clamp(x, 0, 255)))


# ----------------------------------------------------------------------
# RGB <-> HEX
# ----------------------------------------------------------------------

def rgb_to_hex(R, G, B):
    """(255, 128, 0) -> '#FF8000'. Каждый байт записывается двумя цифрами 16-ричной системы."""
    return "#{:02X}{:02X}{:02X}".format(to_byte(R), to_byte(G), to_byte(B))


def hex_to_rgb(text):
    """'#FF8000' или 'ff8000' -> (255, 128, 0)."""
    text = text.strip().lstrip("#")
    if len(text) == 3:                      # короткая запись #F80 = #FF8800
        text = "".join(ch * 2 for ch in text)
    if len(text) != 6:
        raise ValueError("HEX должен содержать 6 цифр, например #FF8000")
    return int(text[0:2], 16), int(text[2:4], 16), int(text[4:6], 16)


# ----------------------------------------------------------------------
# RGB <-> CMYK
# ----------------------------------------------------------------------

def rgb_to_cmyk(R, G, B):
    """
    K — «сколько чёрного»: K = 1 - max(r, g, b).
    Остальные краски — то, чего не хватает до полной яркости, с поправкой на K:
        C = (1 - r - K) / (1 - K), и так же для M, Y.
    Для чистого чёрного (K = 1) делить нельзя (ноль в знаменателе), поэтому C=M=Y=0.
    """
    r, g, b = R / 255, G / 255, B / 255
    k = 1 - max(r, g, b)
    if k == 1:
        return 0.0, 0.0, 0.0, 1.0
    c = (1 - r - k) / (1 - k)
    m = (1 - g - k) / (1 - k)
    y = (1 - b - k) / (1 - k)
    return c, m, y, k


def cmyk_to_rgb(c, m, y, k):
    """Обратно: R = 255 * (1 - C) * (1 - K), и так же для G и B."""
    R = 255 * (1 - c) * (1 - k)
    G = 255 * (1 - m) * (1 - k)
    B = 255 * (1 - y) * (1 - k)
    return to_byte(R), to_byte(G), to_byte(B)


# ----------------------------------------------------------------------
# RGB <-> HSV и RGB <-> HSL
# ----------------------------------------------------------------------

def _hue(r, g, b):
    """
    Оттенок H в градусах 0..360 (одинаков в HSV и HSL).
    Идея: круг оттенков разбит на 6 секторов по 60 градусов.
    Какая компонента максимальна — в таком секторе мы и находимся.
        максимум r:  H = 60 * ((g - b) / d  mod 6)       красный сектор (около 0°)
        максимум g:  H = 60 * ((b - r) / d + 2)          зелёный сектор (около 120°)
        максимум b:  H = 60 * ((r - g) / d + 4)          синий сектор (около 240°)
    где d = max - min. Если d = 0, цвет серый и оттенка нет (берём 0).
    """
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    if d == 0:
        return 0.0
    if mx == r:
        return 60 * (((g - b) / d) % 6)
    if mx == g:
        return 60 * ((b - r) / d + 2)
    return 60 * ((r - g) / d + 4)


def _from_hue(h, c, m):
    """
    Общий шаг обратного перевода HSV/HSL -> RGB.
    c — «цветность» (chroma), m — добавка яркости ко всем каналам.
    x — вторая по величине компонента внутри сектора.
    """
    h = h % 360
    x = c * (1 - abs((h / 60) % 2 - 1))
    sector = int(h // 60)
    r, g, b = [(c, x, 0), (x, c, 0), (0, c, x),
               (0, x, c), (x, 0, c), (c, 0, x)][sector]
    return to_byte((r + m) * 255), to_byte((g + m) * 255), to_byte((b + m) * 255)


def rgb_to_hsv(R, G, B):
    """
    HSV: H — оттенок, S = d / max — насыщенность, V = max — «значение» (яркость самого яркого канала).
    """
    r, g, b = R / 255, G / 255, B / 255
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    s = 0.0 if mx == 0 else d / mx
    return _hue(r, g, b), s, mx


def hsv_to_rgb(h, s, v):
    """C = V * S — цветность; m = V - C — сколько белого добавлено ко всем каналам."""
    c = v * s
    return _from_hue(h, c, v - c)


def rgb_to_hsl(R, G, B):
    """
    HSL: L = (max + min) / 2 — светлота;
    S = d / (1 - |2L - 1|) — насыщенность относительно возможного для такой светлоты.
    Множитель (1 - |2L - 1|) равен нулю при L = 0 и L = 1 (чёрный и белый), там S = 0.
    """
    r, g, b = R / 255, G / 255, B / 255
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    l = (mx + mn) / 2
    s = 0.0 if d == 0 else d / (1 - abs(2 * l - 1))
    return _hue(r, g, b), s, l


def hsl_to_rgb(h, s, l):
    """C = (1 - |2L - 1|) * S; m = L - C / 2."""
    c = (1 - abs(2 * l - 1)) * s
    return _from_hue(h, c, l - c / 2)


# ----------------------------------------------------------------------
# RGB <-> YCbCr (вариант JPEG, диапазон 0..255)
# ----------------------------------------------------------------------

def rgb_to_ycbcr(R, G, B):
    """
    Y  — яркость (глаз сильнее всего чувствует зелёный, отсюда веса 0.299 / 0.587 / 0.114);
    Cb — «синева» (B - Y, сжатая в диапазон), Cr — «краснота» (R - Y, сжатая);
    128 прибавляется, чтобы серый цвет имел Cb = Cr = 128, а не 0.
    """
    Y = 0.299 * R + 0.587 * G + 0.114 * B
    Cb = 128 - 0.168736 * R - 0.331264 * G + 0.5 * B
    Cr = 128 + 0.5 * R - 0.418688 * G - 0.081312 * B
    return Y, Cb, Cr


def ycbcr_to_rgb(Y, Cb, Cr):
    """Обратное преобразование. Числа 1.402 и 1.772 приходят из делителей 2*(1-0.299) и 2*(1-0.114)."""
    R = Y + 1.402 * (Cr - 128)
    G = Y - 0.344136 * (Cb - 128) - 0.714136 * (Cr - 128)
    B = Y + 1.772 * (Cb - 128)
    return to_byte(R), to_byte(G), to_byte(B)


# ----------------------------------------------------------------------
# sRGB -> линейный свет (нужен для XYZ и LAB)
# ----------------------------------------------------------------------

def srgb_to_linear(c):
    """
    c — доля 0..1 (r, g или b). Экран хранит яркость «со сжатием» (гамма),
    а физически правильный свет — линейный. Две ветки:
        малые значения: прямая c / 12.92 (чтобы функция была гладкой около нуля),
        остальные:      ((c + 0.055) / 1.055) ^ 2.4.
    """
    if c <= 0.04045:
        return c / 12.92
    return ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c):
    """Обратная функция: ветка 12.92 * c для малых и 1.055 * c^(1/2.4) - 0.055 для остальных."""
    if c <= 0.0031308:
        return 12.92 * c
    return 1.055 * c ** (1 / 2.4) - 0.055


# ----------------------------------------------------------------------
# RGB <-> XYZ (белая точка D65)
# ----------------------------------------------------------------------

# Белая точка D65: XYZ «идеально белого» (R=G=B=255). Это суммы строк матрицы ниже.
WHITE_X, WHITE_Y, WHITE_Z = 0.95047, 1.0, 1.08883


def rgb_to_xyz(R, G, B):
    """Сначала снимаем гамму (получаем линейный свет), потом умножаем на матрицу 3x3."""
    r = srgb_to_linear(R / 255)
    g = srgb_to_linear(G / 255)
    b = srgb_to_linear(B / 255)
    X = 0.4124564 * r + 0.3575761 * g + 0.1804375 * b
    Y = 0.2126729 * r + 0.7151522 * g + 0.0721750 * b
    Z = 0.0193339 * r + 0.1191920 * g + 0.9503041 * b
    return X, Y, Z


def xyz_to_rgb(X, Y, Z):
    """Обратная матрица, потом возвращаем гамму."""
    r = 3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z
    g = -0.9692660 * X + 1.8760108 * Y + 0.0415560 * Z
    b = 0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z
    # линейный свет может немного выйти за [0, 1] из-за округлений — обрезаем
    r, g, b = clamp(r, 0, 1), clamp(g, 0, 1), clamp(b, 0, 1)
    return (to_byte(255 * linear_to_srgb(r)),
            to_byte(255 * linear_to_srgb(g)),
            to_byte(255 * linear_to_srgb(b)))


# ----------------------------------------------------------------------
# XYZ <-> LAB
# ----------------------------------------------------------------------

DELTA = 6 / 29     # граница между кубическим корнем и линейным участком


def _f(t):
    """Сжимающая функция LAB: кубический корень, а около нуля — прямая (корень там слишком крутой)."""
    if t > DELTA ** 3:
        return t ** (1 / 3)
    return t / (3 * DELTA ** 2) + 4 / 29


def _f_inv(t):
    """Обратная к _f."""
    if t > DELTA:
        return t ** 3
    return 3 * DELTA ** 2 * (t - 4 / 29)


def xyz_to_lab(X, Y, Z):
    """
    L = 116 * f(Y/Yn) - 16        (светлота 0..100)
    a = 500 * (f(X/Xn) - f(Y/Yn)) (зелёный <-> красный)
    b = 200 * (f(Y/Yn) - f(Z/Zn)) (синий <-> жёлтый)
    """
    fx, fy, fz = _f(X / WHITE_X), _f(Y / WHITE_Y), _f(Z / WHITE_Z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def lab_to_xyz(L, a, b):
    fy = (L + 16) / 116
    fx = fy + a / 500
    fz = fy - b / 200
    return WHITE_X * _f_inv(fx), WHITE_Y * _f_inv(fy), WHITE_Z * _f_inv(fz)


def rgb_to_lab(R, G, B):
    """RGB -> XYZ -> LAB."""
    return xyz_to_lab(*rgb_to_xyz(R, G, B))


def lab_to_rgb(L, a, b):
    """LAB -> XYZ -> RGB."""
    return xyz_to_rgb(*lab_to_xyz(L, a, b))


# ----------------------------------------------------------------------
# «Все со всеми» через хаб RGB
# ----------------------------------------------------------------------

# Для каждой модели: (функция в RGB, функция из RGB)
_TO_RGB = {
    "RGB":   lambda R, G, B: (to_byte(R), to_byte(G), to_byte(B)),
    "CMYK":  cmyk_to_rgb,
    "HSV":   hsv_to_rgb,
    "HSL":   hsl_to_rgb,
    "YCbCr": ycbcr_to_rgb,
    "LAB":   lab_to_rgb,
}
_FROM_RGB = {
    "RGB":   lambda R, G, B: (R, G, B),
    "CMYK":  rgb_to_cmyk,
    "HSV":   rgb_to_hsv,
    "HSL":   rgb_to_hsl,
    "YCbCr": rgb_to_ycbcr,
    "LAB":   rgb_to_lab,
}

MODELS = list(_TO_RGB)   # ['RGB', 'CMYK', 'HSV', 'HSL', 'YCbCr', 'LAB']


def convert(values, from_model, to_model):
    """
    Перевод цвета между любыми двумя моделями из MODELS.

    Пример:  convert((255, 128, 0), "RGB", "HSV")  ->  (30.0, 1.0, 1.0)

    Любая пара проходит через RGB: from -> RGB -> to.
    Поэтому для N моделей нужно 2*N функций, а не N*(N-1).
    """
    if from_model not in _TO_RGB or to_model not in _FROM_RGB:
        raise ValueError("Неизвестная модель. Доступны: " + ", ".join(MODELS))
    rgb = _TO_RGB[from_model](*values)
    return _FROM_RGB[to_model](*rgb)
